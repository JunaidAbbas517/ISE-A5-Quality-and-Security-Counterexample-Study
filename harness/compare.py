"""Build results/COMPARISON.md and results/comparison.csv from the raw JSON results (nothing typed by hand).

  python harness/compare.py
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / 'results' / 'raw'
CLAIMS = {
    'C1': 'Role, email, status not client-writable', 'C2': 'Deadline only via change_deadline()',
    'C3': 'Users see/change only their own data', 'C4': 'Pending/revoked instructor manages nothing',
    'C5': 'Admin never chosen at sign-up', 'C6': 'Anonymous key gets nothing',
    'C7': 'Grades hidden until returned; RPC-only writes',
}


def latest_runs(config: str) -> list[dict]:
    files = sorted(RAW.glob(f'*-{config}-run*.json'))
    runs = [json.loads(p.read_text(encoding='utf-8')) for p in files]
    # keep the most recent invocation (same environment.utc)
    if runs:
        last = runs[-1]['environment']['utc']
        runs = [r for r in runs if r['environment']['utc'] == last]
    return runs


def main() -> int:
    import sys
    sys.stdout.reconfigure(encoding='utf-8')
    before, after = latest_runs('before'), latest_runs('after')
    mut = json.loads(sorted(RAW.glob('*-mutants.json'))[-1].read_text(encoding='utf-8'))
    b, a = before[0], after[0]
    det_b = all([r['verdict'] for r in x['results']] == [r['verdict'] for r in b['results']] for x in before)
    det_a = all([r['verdict'] for r in x['results']] == [r['verdict'] for r in a['results']] for x in after)

    rows = []
    for rb, ra in zip(b['results'], a['results']):
        assert rb['id'] == ra['id']
        rows.append({'id': rb['id'], 'claim': rb['claim'], 'kind': rb['kind'], 'actor': rb['actor'],
                     'before': rb['verdict'], 'after': ra['verdict'],
                     'changed': 'yes' if rb['verdict'] != ra['verdict'] else ''})
    with (ROOT / 'results' / 'comparison.csv').open('w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    def sec(runs):
        s = [r['summary']['seconds'] for r in runs]
        return f"{min(s):.2f}–{max(s):.2f}"

    out = ['# Before / after comparison', '',
           '_Generated by `python harness/compare.py` from `results/raw/`. Do not edit by hand._', '',
           '| | Before (frozen app) | After (+ improvement 001) |', '|---|---|---|',
           f"| Raw files | {', '.join(Path(p).name for p in sorted(RAW.glob('*-before-run*.json'))[-len(before):])} | "
           f"{', '.join(Path(p).name for p in sorted(RAW.glob('*-after-run*.json'))[-len(after):])} |",
           f"| Runs / identical verdicts | {len(before)} / {det_b} | {len(after)} / {det_a} |",
           f"| Cases (attack + control) | {b['summary']['attack_cases']} + {b['summary']['control_cases']} | "
           f"{a['summary']['attack_cases']} + {a['summary']['control_cases']} |",
           f"| Run valid (all controls pass) | {b['summary']['run_valid']} | {a['summary']['run_valid']} |",
           f"| **Counterexamples** | **{len(b['summary']['counterexamples'])}** ({', '.join(b['summary']['counterexamples']) or '-'}) | "
           f"**{len(a['summary']['counterexamples'])}** ({', '.join(a['summary']['counterexamples']) or '-'}) |",
           f"| Control failures (side effects) | {len(b['summary']['control_failures'])} | {len(a['summary']['control_failures'])} |",
           f"| Seconds per run (build + 67 cases) | {sec(before)} | {sec(after)} |",
           '', '## Per claim', '', '| Claim | Statement | Attack cases | Counterexamples before | after | Verdict before → after |',
           '|---|---|---|---|---|---|']
    for c, text in CLAIMS.items():
        n = sum(1 for r in rows if r['claim'] == c and r['kind'] != 'control')
        cb = [r['id'] for r in rows if r['claim'] == c and r['kind'] != 'control' and r['before'] == 'FAIL']
        ca = [r['id'] for r in rows if r['claim'] == c and r['kind'] != 'control' and r['after'] == 'FAIL']
        verdict = lambda x: 'falsified' if x else 'not falsified'
        out.append(f"| {c} | {text} | {n} | {len(cb)} {('(' + ', '.join(cb) + ')') if cb else ''} | {len(ca)} | "
                   f"{verdict(cb)} → {verdict(ca)} |")
    out += ['', '## Cases whose verdict changed', '', '| Case | Claim | Actor | Before | After |', '|---|---|---|---|---|']
    out += [f"| {r['id']} | {r['claim']} | {r['actor']} | {r['before']} | {r['after']} |" for r in rows if r['changed']]
    out += ['', '## Oracle strength (mutation set, run on the frozen app)', '',
            f"Score **{mut['killed']}/{mut['valid']} = {mut['score']}** (threshold 0.80).", '',
            '| Mutant | Guard weakened | Result | Killed by |', '|---|---|---|---|']
    out += [f"| {m['id']} | {m['guard']} | {m['status']} | {', '.join(m['killed_by']) or '-'} |" for m in mut['mutants']]
    out.append('')
    (ROOT / 'results' / 'COMPARISON.md').write_text('\n'.join(out), encoding='utf-8')
    print('\n'.join(out))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
